export function calculateScore(userAnswers: Record<number, 'A' | 'B' | 'C' | 'D' | null>, timeSpentSeconds: number) {
  let correctCount = 0;
  let incorrectCount = 0;
  let unansweredCount = 0;

  const categoryScoresMap: Record<string, { correct: number; total: number; title: string; topicVi: string }> = {};

  PASSAGES.forEach((p) => {
    categoryScoresMap[p.id] = {
      correct: 0,
      total: p.questionIds.length,
      title: p.title,
      topicVi: p.topicVi
    };
  });

  QUESTIONS.forEach((q) => {
    const selected = userAnswers[q.id];
    if (!selected) {
      unansweredCount++;
    } else if (selected === q.correctAnswer) {
      correctCount++;
      if (categoryScoresMap[q.passageId]) {
        categoryScoresMap[q.passageId].correct++;
      }
    } else {
      incorrectCount++;
    }
  });

  const total = QUESTIONS.length; // 30
  // Scale out of 10: (correct / 30) * 10
  const scoreOutOf10 = Number(((correctCount / total) * 10).toFixed(2));
  const rawScorePercent = Number(((correctCount / total) * 100).toFixed(1));

  let scoreRating: 'Xuất sắc' | 'Giỏi' | 'Khá' | 'Trung bình' | 'Cần cố gắng';
  let scoreColor: string;

  if (scoreOutOf10 >= 9.0) {
    scoreRating = 'Xuất sắc';
    scoreColor = 'text-emerald-600 dark:text-emerald-400 bg-emerald-50 dark:bg-emerald-950/40 border-emerald-300 dark:border-emerald-800';
  } else if (scoreOutOf10 >= 8.0) {
    scoreRating = 'Giỏi';
    scoreColor = 'text-blue-600 dark:text-blue-400 bg-blue-50 dark:bg-blue-950/40 border-blue-300 dark:border-blue-800';
  } else if (scoreOutOf10 >= 6.5) {
    scoreRating = 'Khá';
    scoreColor = 'text-amber-600 dark:text-amber-400 bg-amber-50 dark:bg-amber-950/40 border-amber-300 dark:border-amber-800';
  } else if (scoreOutOf10 >= 5.0) {
    scoreRating = 'Trung bình';
    scoreColor = 'text-orange-600 dark:text-orange-400 bg-orange-50 dark:bg-orange-950/40 border-orange-300 dark:border-orange-800';
  } else {
    scoreRating = 'Cần cố gắng';
    scoreColor = 'text-rose-600 dark:text-rose-400 bg-rose-50 dark:bg-rose-950/40 border-rose-300 dark:border-rose-800';
  }

  const categoryScores = Object.entries(categoryScoresMap).map(([id, data]) => ({
    passageId: id,
    passageTitle: data.title,
    topicVi: data.topicVi,
    correct: data.correct,
    total: data.total
  }));

  return {
    totalQuestions: total,
    correctCount,
    incorrectCount,
    unansweredCount,
    rawScorePercent,
    scoreOutOf10,
    scoreRating,
    scoreColor,
    timeSpentSeconds,
    dateCompleted: new Date().toLocaleString('vi-VN'),
    categoryScores
  };
}
